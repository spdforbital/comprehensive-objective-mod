"""Builds scripts/comprehensive_objectives/door_graph.lua: which interiors connect to which,
so the objective panel can point at the right door when the target is a few cells away.
All exterior cells are one node, '@ext'."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import world as W

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts', 'comprehensive_objectives', 'door_graph.lua')

def node(ck):
    return '@ext' if ck[0] == 'e' else ck[1].lower()

def main():
    w = W.world()
    adj = {}
    for dest, lst in w['doors_into'].items():
        for frm, _pos, _d in lst:
            a, b = node(frm), node(dest)
            if a != b:
                adj.setdefault(a, set()).add(b)
    names = sorted(set(adj) | {b for s in adj.values() for b in s})
    idx = {n: i + 1 for i, n in enumerate(names)}
    def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    with open(OUT + '.tmp', 'w', encoding='utf-8') as f:
        f.write('-- GENERATED by tools/build_doorgraph.py. names[i] = lowercase cell name; links[i] = "j,k,..." cells its doors lead to\n')
        f.write('local names = {\n')
        for n in names: f.write(q(n) + ',\n')
        f.write('}\nlocal links = {\n')
        for n in names:
            f.write(q(','.join(str(idx[b]) for b in sorted(adj.get(n, ()), key=idx.get))) + ',\n')
        f.write('}\nreturn { names = names, links = links }\n')
    os.replace(OUT + '.tmp', OUT)
    print('cells', len(names), 'links', sum(len(s) for s in adj.values()), 'size', os.path.getsize(OUT))

main()
