"""Builds scripts/comprehensive_objectives/people_data.lua for the Collector's Ledger's People tab:
every named NPC placed in the world, with class, faction, services and where they stand
(plus the doors that lead there from outdoors, for markers).

Usage (from tools/): python3 build_people.py      (needs world.pickle: python3 world.py build)
"""
import math, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from esm import load_order, records, subs, zstr
import world as Wm

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts', 'comprehensive_objectives', 'people_data.lua')
MAX_CELLS = 3          # people placed in more cells than this are generic copies (not listed)

# AIDT service flags
BARTER = 0x1 | 0x2 | 0x4 | 0x8 | 0x10 | 0x20 | 0x40 | 0x80 | 0x100 | 0x200 | 0x400 | 0x1000 | 0x2000
SPELLS, TRAINING, SPELLMAKING, ENCHANTING, REPAIR = 0x800, 0x4000, 0x8000, 0x10000, 0x20000


def scan():
    npcs, classes, factions, regions, cellnames = {}, {}, {}, {}, {}
    for plugin, path in load_order():
        for tag, body in records(path):
            if tag == 'NPC_':
                d = {'svc': 0, 'cls': '', 'fac': '', 'dead': False, 'travel': False}
                rid = None; dele = False
                for st, v in subs(body):
                    if st == 'NAME' and rid is None: rid = zstr(v)
                    elif st == 'FNAM': d['name'] = zstr(v)
                    elif st == 'CNAM': d['cls'] = zstr(v).lower()
                    elif st == 'ANAM': d['fac'] = zstr(v).lower()
                    elif st == 'AIDT' and len(v) >= 12: d['svc'] = struct.unpack_from('<i', v, 8)[0]
                    elif st == 'DODT': d['travel'] = True
                    elif st == 'NPDT' and len(v) >= 52: d['dead'] = struct.unpack_from('<H', v, 38)[0] == 0
                    elif st == 'DELE': dele = True
                if not rid: continue
                if dele: npcs.pop(rid.lower(), None); continue
                npcs[rid.lower()] = d
            elif tag in ('CLAS', 'FACT'):
                rid = name = None
                for st, v in subs(body):
                    if st == 'NAME' and rid is None: rid = zstr(v)
                    elif st == 'FNAM': name = zstr(v)
                if rid and name:
                    (classes if tag == 'CLAS' else factions)[rid.lower()] = name
            elif tag == 'REGN':
                rid = name = None
                for st, v in subs(body):
                    if st == 'NAME' and rid is None: rid = zstr(v)
                    elif st == 'FNAM': name = zstr(v)
                if rid: regions[rid.lower()] = name or rid
    return npcs, classes, factions, regions


def q(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'


def main():
    W = Wm.world()
    npcs, classes, factions, regions = scan()
    cell_idx, cell_rows = {}, []

    def outdoor_name(gx, gy):
        m = W['cells'].get(('e', (gx, gy)), {})
        return m.get('name') or ''

    def cidx(ck):
        if ck in cell_idx: return cell_idx[ck]
        if ck[0] == 'e':
            row = {'n': outdoor_name(*ck[1]) or 'Wilderness', 'e': True}
        else:
            row = {'n': W['cells'][ck]['name'], 'id': ck[1], 'D': []}
            try:
                route = Wm.entrances(ck)
            except Exception:
                route = []
            for dck, dpos in route[:12]:
                row['D'].append(('e' if dck[0] == 'e' else None, dck, dpos))
            for dck, dpos in route:
                if dck[0] == 'e':
                    row['near'] = outdoor_name(int(dpos[0] // 8192), int(dpos[1] // 8192))
                    break
        cell_rows.append(row)
        cell_idx[ck] = len(cell_rows)
        return cell_idx[ck]

    people = []
    skipped_generic = 0
    for rid, d in npcs.items():
        name = (d.get('name') or '').strip()
        if not name: continue
        pl = W['placed'].get(rid, [])
        if not pl: continue
        cells = []
        for ck, _ in pl:
            if ck not in cells: cells.append(ck)
        if len(cells) > MAX_CELLS:
            skipped_generic += 1
            continue
        fl = 0
        if d['svc'] & BARTER: fl |= 1
        if d['svc'] & TRAINING: fl |= 2
        if d['svc'] & SPELLS: fl |= 4
        if d['svc'] & SPELLMAKING: fl |= 8
        if d['svc'] & ENCHANTING: fl |= 16
        if d['svc'] & REPAIR: fl |= 32
        if d['travel']: fl |= 64
        if d['dead']: fl |= 128
        cls = classes.get(d['cls'], d['cls'])
        fac = factions.get(d['fac'], d['fac'])
        for ck, p in pl[:MAX_CELLS]:
            people.append((name, rid, cidx(ck), p, cls, fac, fl))
    people.sort(key=lambda r: (r[0].lower(), r[1]))

    # door cells referenced by route doors need indices too
    lines = ['-- GENERATED by tools/build_people.py from the active load order. Do not edit by hand.',
             '-- cells[i] = { n = name, id = interior id (lowercase), e = exterior, near = outdoor area,',
             "--              D = route doors from outdoors 'cell|e,x,y,z;...' }",
             "-- people[i] = 'name|record id|cell|x|y|z|class|faction|flags'  flags: 1 merchant 2 trainer 4 spells",
             '--              8 spellmaking 16 enchanting 32 repair 64 travel 128 dead',
             'local cells = {}']
    # resolve route-door cells after all people cells exist
    for row in list(cell_rows):
        if row.get('e'): continue
        parts = []
        for ext, dck, dpos in row['D']:
            c = 'e' if ext else str(cidx(dck))
            parts.append(f"{c},{dpos[0]:.0f},{dpos[1]:.0f},{dpos[2]:.0f}")
        row['Ds'] = ';'.join(parts)
    for i, row in enumerate(cell_rows, 1):
        f = [f"n = {q(row['n'])}"]
        if row.get('e'): f.append('e = true')
        else:
            f.append(f"id = {q(row['id'])}")
            if row.get('near'): f.append(f"near = {q(row['near'])}")
            if row.get('Ds'): f.append(f"D = {q(row['Ds'])}")
        lines.append(f"cells[{i}] = {{ {', '.join(f)} }}")
    lines.append('local people = {')
    for name, rid, c, p, cls, fac, fl in people:
        s = '|'.join([name.replace('|', ' '), rid, str(c), f'{p[0]:.0f}', f'{p[1]:.0f}', f'{p[2]:.0f}',
                      (cls or '').replace('|', ' '), (fac or '').replace('|', ' '), str(fl)])
        lines.append('  ' + q(s) + ',')
    lines.append('}')
    lines.append('return { cells = cells, people = people }')
    tmp = OUT + '.tmp'
    open(tmp, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    os.replace(tmp, OUT)
    print(f'people {len(people)} (generic copies skipped {skipped_generic}), cells {len(cell_rows)}, '
          f'{os.path.getsize(OUT) / 1e6:.2f} MB -> {OUT}')


if __name__ == '__main__':
    main()
